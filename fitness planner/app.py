def ask_groq(prompt):
    headers = {
        'Authorization': f'Bearer {GROQ_API_KEY}',
        'Content-Type': 'application/json',
    }
    data = {
        'model': GROQ_MODEL,
        'messages': [
            {'role': 'system', 'content': 'شما یک مشاور ورزشی و تغذیه حرفه‌ای هستید.'},
            {'role': 'user', 'content': prompt},
        ],
        'max_tokens': 2048,
        'temperature': 0.7,
    }
    try:
        response = requests.post(GROQ_API_URL, headers=headers, json=data, timeout=60)
        response.raise_for_status()
        result = response.json()
        return result['choices'][0]['message']['content'], None
    except Exception as e:
        return None, str(e)

def extract_sections(ai_response):
    if not ai_response:
        return []
    pattern = r'<\s*section[^>]*>(.*?)<\s*/\s*section>'
    matches = re.findall(pattern, ai_response, re.DOTALL | re.IGNORECASE)
    if matches:
        return [f'<section>{m.strip()}</section>' for m in matches]
    else:
        return [ai_response]

